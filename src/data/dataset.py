"""
Dataset classes for defect detection
"""

import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import cv2
import numpy as np
import torch
from PIL import Image
from torch.utils.data import DataLoader, Dataset

from .augmentation import (
    apply_random_defect,
    get_training_augmentation,
    get_validation_augmentation,
)


class SyntheticDefectDataset(Dataset):
    """Dataset for synthetic defect detection"""

    def __init__(
        self,
        root_dir: str,
        split: str = "train",
        img_size: int = 224,
        augment: bool = True,
        generate_on_fly: bool = False,
        num_samples: Optional[int] = None,
        seed: int = 42,
    ):
        """
        Args:
            root_dir: Directory containing dataset
            split: 'train', 'val', or 'test'
            img_size: Image size for resizing
            augment: Whether to apply augmentations
            generate_on_fly: Generate synthetic data on the fly instead of loading from disk
            num_samples: Number of samples to generate (for on-the-fly generation)
        """
        self.root_dir = Path(root_dir)
        if split not in {"train", "val", "test"}:
            raise ValueError("split must be one of: train, val, test")
        if not isinstance(img_size, int) or img_size <= 0:
            raise ValueError("img_size must be a positive integer")
        if not isinstance(seed, int):
            raise ValueError("seed must be an integer")
        self.split = split
        self.img_size = img_size
        self.augment = augment and split == "train"
        self.generate_on_fly = generate_on_fly
        self.seed = seed % (2**32)

        # Class mapping
        self.classes = ["ok", "scratch", "crack", "dent", "corrosion"]
        self.class_to_idx = {cls: idx for idx, cls in enumerate(self.classes)}

        if self.generate_on_fly:
            self.num_samples = (
                num_samples if num_samples is not None else (10000 if split == "train" else 2000)
            )
            if not isinstance(self.num_samples, int) or self.num_samples <= 0:
                raise ValueError("num_samples must be a positive integer")
            self.samples = self._generate_sample_list()
        else:
            self.samples = self._load_sample_list()

        # Setup augmentations
        if self.augment:
            self.transform = get_training_augmentation(img_size)
        else:
            self.transform = get_validation_augmentation(img_size)

    def _generate_sample_list(self) -> List[Dict[str, Any]]:
        """Generate list of synthetic samples"""
        samples = []

        # Class distribution (balanced for training, realistic for val/test)
        if self.split == "train":
            # Balanced distribution
            class_counts = {cls: self.num_samples // len(self.classes) for cls in self.classes}
        else:
            # More realistic distribution (more OK samples)
            total_samples = self.num_samples
            ok_samples = int(total_samples * 0.7)  # 70% OK
            defect_samples = (total_samples - ok_samples) // (len(self.classes) - 1)

            class_counts = {"ok": ok_samples}
            for cls in self.classes[1:]:
                class_counts[cls] = defect_samples

        # Adjust for rounding
        total_assigned = sum(class_counts.values())
        if total_assigned < self.num_samples:
            class_counts["ok"] += self.num_samples - total_assigned

        # Generate sample list
        sample_id = 0
        for cls, count in class_counts.items():
            for i in range(count):
                samples.append(
                    {
                        "id": sample_id,
                        "class": cls,
                        "label": self.class_to_idx[cls],
                        "path": None,  # Will be generated on the fly
                        "generated": True,
                    }
                )
                sample_id += 1

        # Keep sample order reproducible without changing NumPy's process-wide RNG.
        np.random.default_rng(self.seed).shuffle(samples)
        return samples

    def _load_sample_list(self) -> List[Dict[str, Any]]:
        """Load sample list from annotations file"""
        annotations_file = self.root_dir / f"{self.split}_annotations.json"

        # Datasets generated by older versions stored annotations in a subdirectory.
        if not annotations_file.exists():
            annotations_file = self.root_dir / "annotations" / f"{self.split}_annotations.json"

        if not annotations_file.exists():
            raise FileNotFoundError(f"Annotations file not found: {annotations_file}")

        with open(annotations_file, "r", encoding="utf-8") as f:
            data = json.load(f)

        if not isinstance(data, list) or not data:
            raise ValueError(f"Annotations must be a non-empty JSON list: {annotations_file}")

        samples = []
        root_path = self.root_dir.resolve()
        for index, item in enumerate(data):
            if not isinstance(item, dict):
                raise ValueError(f"Annotation {index} must be an object")
            class_name = item.get("class")
            if class_name not in self.class_to_idx:
                raise ValueError(f"Annotation {index} has unknown class: {class_name!r}")
            image_path = item.get("path")
            if not isinstance(image_path, str) or not image_path.strip():
                raise ValueError(f"Annotation {index} must contain a non-empty path")

            resolved_path = (self.root_dir / image_path).resolve()
            if not resolved_path.is_relative_to(root_path):
                raise ValueError(
                    f"Annotation {index} points outside the dataset root: {image_path}"
                )
            if not resolved_path.is_file():
                raise FileNotFoundError(f"Annotation {index} image not found: {resolved_path}")
            expected_label = self.class_to_idx[class_name]
            if "label" in item and item["label"] != expected_label:
                raise ValueError(
                    f"Annotation {index} label {item['label']!r} does not match class {class_name!r}"
                )

            samples.append(
                {
                    "id": item.get("id", index),
                    "class": class_name,
                    "label": expected_label,
                    "path": str(resolved_path),
                    "generated": False,
                }
            )

        return samples

    def _generate_base_image(self) -> np.ndarray:
        """Generate a base metal surface image"""
        # Create base metallic color
        base_color = np.random.randint(150, 220, 3)  # Light gray to light blue-gray

        # Create base image
        img = np.full((self.img_size, self.img_size, 3), base_color, dtype=np.uint8)

        # Add metallic texture
        noise = np.random.normal(0, 30, (self.img_size, self.img_size, 3))
        img = np.clip(img.astype(np.float32) + noise, 0, 255)

        # Add subtle gradients (lighting effects)
        gradient = np.linspace(0.8, 1.2, self.img_size).reshape(-1, 1)
        gradient = np.repeat(gradient, self.img_size, axis=1)
        img = np.clip(img * gradient[:, :, np.newaxis], 0, 255).astype(np.uint8)

        return img

    def _load_image(self, path: str) -> np.ndarray:
        """Load image from disk"""
        img = cv2.imread(path)
        if img is None:
            raise FileNotFoundError(f"Could not load image: {path}")
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
        return img

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, int, Dict]:
        """Get a single sample"""
        sample = self.samples[idx]

        if self.generate_on_fly or sample.get("generated", False):
            rng_state = None
            if self.split != "train":
                rng_state = np.random.get_state()
                split_offset = {"val": 1_000_000, "test": 2_000_000}[self.split]
                np.random.seed((self.seed + split_offset + sample["id"]) % (2**32))
            try:
                base_img = self._generate_base_image()
                if sample["class"] == "ok":
                    img = base_img
                else:
                    img, _ = apply_random_defect(base_img, sample["class"])
            finally:
                if rng_state is not None:
                    np.random.set_state(rng_state)
        else:
            # Load from disk
            img = self._load_image(sample["path"])

        img_tensor = self.transform(Image.fromarray(img))

        # Metadata
        metadata = {"id": sample["id"], "class": sample["class"], "path": sample.get("path") or ""}

        return img_tensor, sample["label"], metadata


class DefectDetectionDataset:
    """Wrapper class for creating train/val/test datasets"""

    def __init__(self, config: Dict):
        self.config = config

    def get_datasets(self) -> Tuple[Dataset, Dataset, Dataset]:
        """Get train, validation, and test datasets"""
        data_config = self.config.get("data", {})
        img_size = data_config.get("img_size", self.config.get("model", {}).get("img_size", 224))

        train_dataset = SyntheticDefectDataset(
            root_dir=data_config.get("root_dir", "./data"),
            split="train",
            img_size=img_size,
            augment=True,
            generate_on_fly=data_config.get("generate_on_fly", True),
            num_samples=data_config.get("train_samples", 10000),
            seed=data_config.get("seed", 42),
        )

        val_dataset = SyntheticDefectDataset(
            root_dir=data_config.get("root_dir", "./data"),
            split="val",
            img_size=img_size,
            augment=False,
            generate_on_fly=data_config.get("generate_on_fly", True),
            num_samples=data_config.get("val_samples", 2000),
            seed=data_config.get("seed", 42),
        )

        test_dataset = SyntheticDefectDataset(
            root_dir=data_config.get("root_dir", "./data"),
            split="test",
            img_size=img_size,
            augment=False,
            generate_on_fly=data_config.get("generate_on_fly", True),
            num_samples=data_config.get("test_samples", 2000),
            seed=data_config.get("seed", 42),
        )

        return train_dataset, val_dataset, test_dataset

    def get_dataloaders(
        self,
        batch_size: Optional[int] = None,
        num_workers: Optional[int] = None,
    ) -> Tuple[DataLoader, DataLoader, DataLoader]:
        """Get train, validation, and test dataloaders"""
        train_dataset, val_dataset, test_dataset = self.get_datasets()
        data_config = self.config.get("data", {})
        batch_size = data_config.get("batch_size", 32) if batch_size is None else batch_size
        num_workers = data_config.get("num_workers", 4) if num_workers is None else num_workers
        pin_memory = bool(data_config.get("pin_memory", False))

        train_loader = DataLoader(
            train_dataset,
            batch_size=batch_size,
            shuffle=True,
            num_workers=num_workers,
            pin_memory=pin_memory,
            drop_last=False,
        )

        val_loader = DataLoader(
            val_dataset,
            batch_size=batch_size,
            shuffle=False,
            num_workers=num_workers,
            pin_memory=pin_memory,
        )

        test_loader = DataLoader(
            test_dataset,
            batch_size=batch_size,
            shuffle=False,
            num_workers=num_workers,
            pin_memory=pin_memory,
        )

        return train_loader, val_loader, test_loader
